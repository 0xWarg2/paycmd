function interpolate(template: string, params?: Params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ""));
}

export function resolvePayCmdLocale(value?: string | null): PayCmdLocale {
  const normalized = value?.toLowerCase() ?? "";
  return normalized.startsWith("en") ? "en" : "vi";
}

export function requestLocale(request: Request): PayCmdLocale {
  const headerLocale = request.headers.get("x-paycmd-locale");
  if (headerLocale) return resolvePayCmdLocale(headerLocale);

  const cookieLocale = request.headers
    .get("cookie")
    ?.split(";")
    .map((item) => item.trim())
    .find((item) => item.startsWith("paycmd_locale="))
    ?.split("=")[1];
  if (cookieLocale) return resolvePayCmdLocale(cookieLocale);

  return resolvePayCmdLocale(request.headers.get("accept-language"));
}

export function tr(locale: PayCmdLocale, key: string, params?: Params) {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return interpolate(template, params);
}

export function localeFromCookieStore(cookieStore: { get: (name: string) => { value?: string } | undefined }) {
  return resolvePayCmdLocale(cookieStore.get("paycmd_locale")?.value);
}
