type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Record<string, string | number | undefined | null>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(template: string, params?: Record<string, string | number | undefined | null>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ""));
}

export function resolveLocale(value?: string | null): Locale {
  return value === "en" || value === "vi" ? value : "vi";
}

export function localeFromStorage(): Locale {
  if (typeof window === "undefined") return "vi";
  return resolveLocale(window.localStorage.getItem(localeStorageKey));
}

function persistLocaleCookie(locale: Locale) {
  if (typeof document === "undefined") return;
  document.cookie = `${localeStorageKey}=${locale}; path=/; max-age=31536000; SameSite=Lax`;
}

export function localeRequestHeaders(): Record<string, string> {
  return { "x-paycmd-locale": localeFromStorage() };
}

export function translateClient(
  key: string,
  params?: Record<string, string | number | undefined | null>,
) {
  const locale = localeFromStorage();
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  return interpolate(template, params);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("vi");

  useEffect(() => {
    setLocaleState(localeFromStorage());
  }, []);

  const value = useMemo<I18nContextValue>(() => {
    const setLocale = (nextLocale: Locale) => {
      setLocaleState(nextLocale);
      window.localStorage.setItem(localeStorageKey, nextLocale);
      persistLocaleCookie(nextLocale);
      document.documentElement.lang = nextLocale;
    };

    return {
      locale,
      setLocale,
      t: (key, params) => {
        const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
        return interpolate(template, params);
      },
    };
  }, [locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    persistLocaleCookie(locale);
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}

